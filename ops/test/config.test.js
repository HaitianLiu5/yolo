import { generatedDrift, InstanceConfigError, readTemplate, renderInstanceConfig, renderLocalConfig, serializeGenerated } from "../lib/wrangler-config.js";

const template = readTemplate(join(ROOT, "service/control/wrangler.jsonc"));
const example = JSON.parse(readFileSync(join(ROOT, "yolo.instance.example.json"), "utf8"));

test("JSONC keeps strings and drops comments and trailing commas", () => {
  const value = parseJsonc(`// head\n{ "url": "https://a.test//x", /* note */ "list": [1, 2,], "s": "a\\"//b", }\n`);
  assert.deepEqual(value, { url: "https://a.test//x", list: [1, 2], s: "a\"//b" });
});

test("the tracked wrangler template carries no instance's values", () => {
  assert.equal(template.routes, undefined);
  assert.equal(template.vpc_services, undefined);
  assert.equal(template.account_id, undefined);
  assert.equal(template.vars.PUBLIC_ORIGIN, "");
  assert.match(template.d1_databases[0].database_id, /^0{8}-0{4}-0{4}-0{4}-0{12}$/);
  assert.match(template.kv_namespaces[0].id, /^0{32}$/);
  // Every value in the template and its comments is generic: no ids but the
  // all-zero placeholders, and no owner's domain.
  const text = readFileSync(join(ROOT, "service/control/wrangler.jsonc"), "utf8");
  const ids = text.match(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|[0-9a-f]{32}/g) ?? [];
  assert.deepEqual(ids.filter((id) => /[1-9a-f]/.test(id)), []);
  assert.doesNotMatch(text, /haitian/i);
});

test("an instance renders the route, origin, ids and VPC binding onto the template", () => {
  const config = renderInstanceConfig(template, example);
  assert.deepEqual(config.routes, [{ pattern: "yolo.example.com", custom_domain: true }]);
  assert.equal(config.account_id, example.accountId);
  assert.equal(config.vars.PUBLIC_ORIGIN, "https://yolo.example.com");
  assert.equal(config.vars.NODE_TRANSPORT, "vpc");
  assert.equal(config.vars.NODE_ORIGIN, "http://127.0.0.1:9191");
  assert.equal(config.vars.LAN_ACME_DIRECTORY, template.vars.LAN_ACME_DIRECTORY);
  assert.equal(config.vars.WAN_CERTIFICATE, "name");
  assert.equal(renderInstanceConfig(template, { ...example, media: { wan: { certificate: "ip" } } }).vars.WAN_CERTIFICATE, "ip");
  assert.equal(config.d1_databases[0].database_id, example.d1.id);
  assert.equal(config.d1_databases[0].migrations_dir, "migrations");
  assert.equal(config.kv_namespaces[0].id, example.kv.id);
  assert.deepEqual(config.vpc_services, [{ binding: "NODE", service_id: example.vpc.serviceId }]);
  // Everything else comes from the template unchanged.
  for (const key of ["main", "compatibility_date", "compatibility_flags", "assets", "build", "durable_objects", "migrations", "triggers", "observability", "ratelimits"]) {
    assert.deepEqual(config[key], template[key], key);
  }
  assert.match(serializeGenerated(config), /^\/\/ Generated by `npm run yolo -- config render`/);
});

test("an incomplete instance names each missing field and its fix", () => {
  assert.throws(() => renderInstanceConfig(template, { version: 1, domain: "yolo.example.com" }), (error) => {
    assert.ok(error instanceof InstanceConfigError);
    assert.deepEqual(error.problems.map((problem) => problem.field), ["d1.id", "kv.id", "vpc.serviceId"]);
    assert.match(error.problems[0].fix, /provision d1/);
    return true;
  });
  assert.deepEqual(validateInstance({ version: 1, domain: "https://x.example.com/" }).map((problem) => problem.field), ["domain"]);
  assert.deepEqual(validateInstance({ version: 1, domain: "x.example.com", node: { port: 70000 } }).map((problem) => problem.field), ["node.port"]);
  assert.equal(withDefaults({ domain: "x.example.com" }).services.node, "app.useyolo.node");
});

test("the tunnel transport renders no VPC binding", () => {
  const config = renderInstanceConfig(template, { ...example, transport: "tunnel", nodePublicOrigin: "https://node.example.com" });
  assert.equal(config.vpc_services, undefined);
  assert.equal(config.vars.NODE_PUBLIC_ORIGIN, "https://node.example.com");
});

test("an owner's old wrangler config imports into an instance file", () => {
  const old = {
    name: "yolo-control",
    routes: [{ pattern: "yolo.owner.test", custom_domain: true }],
    vars: { PUBLIC_ORIGIN: "https://yolo.owner.test", NODE_TRANSPORT: "vpc", NODE_ORIGIN: "http://127.0.0.1:9191" },
    d1_databases: [{ binding: "DB", database_name: "yolo", database_id: "11111111-2222-4333-8444-555555555555" }],
    kv_namespaces: [{ binding: "OAUTH_KV", id: "abcdefabcdefabcdefabcdefabcdefab" }],
    vpc_services: [{ binding: "NODE", service_id: "66666666-7777-4888-9999-000000000000" }],
  };
  const raw = instanceFromWranglerConfig(old);
  assert.deepEqual(raw, {
    version: 1,
    domain: "yolo.owner.test",
    d1: { name: "yolo", id: "11111111-2222-4333-8444-555555555555" },
    kv: { id: "abcdefabcdefabcdefabcdefabcdefab" },
    vpc: { serviceId: "66666666-7777-4888-9999-000000000000" },
  });
  // Rendering the import gives back the old bindings and route.
  const config = renderInstanceConfig(template, raw);
  assert.deepEqual(config.routes, old.routes);
  assert.equal(config.vars.PUBLIC_ORIGIN, old.vars.PUBLIC_ORIGIN);
  assert.deepEqual(config.vpc_services, old.vpc_services);
});

test("a local config from the template never reaches Cloudflare", () => {
  const controlDir = join(ROOT, "service/control");
  const config = renderLocalConfig(template, { controlDir, name: "local", migrationsDir: "/tmp/m", d1Id: "local-d1", kvId: "local-kv", node: "/usr/bin/node" });
  for (const key of ["routes", "vpc_services", "triggers", "account_id"]) assert.equal(config[key], undefined, key);
  assert.equal(config.main, join(controlDir, "src/index.js"));
  assert.equal(config.assets.directory, join(ROOT, "clients/player/dist"));
  assert.deepEqual(config.assets.run_worker_first, template.assets.run_worker_first);
  assert.equal(config.build.cwd, controlDir);
  assert.doesNotMatch(config.build.command, /(^|&& )node /);
  assert.equal(config.d1_databases[0].migrations_dir, "/tmp/m");
});

test("the generated config is stale when the instance changes", (t) => {
  const dir = mkdtempSync(join(tmpdir(), "yolo-ops-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const file = join(dir, "wrangler.instance.jsonc");
  assert.match(generatedDrift(file, template, example), /not been rendered/);
  writeFileSync(file, serializeGenerated(renderInstanceConfig(template, example)));
  assert.equal(generatedDrift(file, template, example), null);
  assert.match(generatedDrift(file, template, { ...example, node: { port: 9300 } }), /older/);
});

test(".env values are set in place, and a secret is never replaced", (t) => {
  const dir = mkdtempSync(join(tmpdir(), "yolo-ops-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const env = join(dir, ".env");
  const template = join(dir, ".env.example");
  writeFileSync(template, "# A comment\n# NODE_SECRET=\n# PUBLIC_ORIGIN=https://yolo.example.com\nPLEX_URL=http://localhost:32400\n");
  assert.deepEqual(setEnvValues(env, { NODE_SECRET: "first$&", PUBLIC_ORIGIN: "https://a.test" }, { template, overwrite: ["PUBLIC_ORIGIN"] }), ["NODE_SECRET", "PUBLIC_ORIGIN"]);
  assert.deepEqual(setEnvValues(env, { NODE_SECRET: "second", PUBLIC_ORIGIN: "https://b.test", NODE_PORT: 9300 }, { template, overwrite: ["PUBLIC_ORIGIN"] }), ["PUBLIC_ORIGIN", "NODE_PORT"]);
  assert.deepEqual({ ...readEnvFile(env) }, { NODE_SECRET: "first$&", PUBLIC_ORIGIN: "https://b.test", PLEX_URL: "http://localhost:32400", NODE_PORT: "9300" });
  assert.match(readFileSync(env, "utf8"), /^# A comment\nNODE_SECRET=first\$&\nPUBLIC_ORIGIN=https:\/\/b\.test\n/);
});

test("YOLO_INSTANCE moves the instance file and its records together", () => {
  const p = paths({ root: "/repo", env: { YOLO_INSTANCE: "/home/owner/yolo/yolo.instance.json" } });
  assert.equal(p.instance, "/home/owner/yolo/yolo.instance.json");
  assert.equal(p.deployments, "/home/owner/yolo/.yolo/deployments.jsonl");
  assert.equal(paths({ root: "/repo", env: {} }).instance, "/repo/yolo.instance.json");
});
