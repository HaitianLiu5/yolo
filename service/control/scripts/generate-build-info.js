#!/usr/bin/env node
// Writes src/build-info.generated.js: what the deployed Worker reports at
// /.well-known/yolo. `version` is Yolo's one version (the repository's
// package.json, Agent Note 2026-10-13-versions-and-releases), `commit` the
// checkout's commit when git can say, and `migrations.required` the newest D1
// migration this code needs. wrangler.jsonc runs this in its build command,
// after generate-plugins.js.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const MIGRATIONS = fileURLToPath(new URL("../migrations/", import.meta.url));
export const OUTPUT = fileURLToPath(new URL("../src/build-info.generated.js", import.meta.url));

function commit(root) {
  try {
    return execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || null;
  } catch {
    return null;
  }
}

// Migration names as D1 records them: the file name without ".sql".
function migrationNames(dir = MIGRATIONS) {
  return readdirSync(dir).filter((name) => /^\d+_.*\.sql$/.test(name)).sort().map((name) => name.replace(/\.sql$/, ""));
}

function buildInfo({ root = ROOT, migrations = MIGRATIONS } = {}) {
  const { version } = JSON.parse(readFileSync(`${root}package.json`, "utf8"));
  return { version, commit: commit(root), migrations: { required: migrationNames(migrations).at(-1) ?? null } };
}

// Rewrites the file only when its content changes, so `wrangler dev` does not
// rebuild in a loop.
function generateBuildInfo({ outFile = OUTPUT, ...options } = {}) {
  const info = buildInfo(options);
  const source = `// Generated by service/control/scripts/generate-build-info.js; do not edit.\nexport default ${JSON.stringify(info, null, 2)};\n`;
  let current = null;
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    // First run.
  }
  if (current !== source) writeFileSync(outFile, source);
  return info;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const info = generateBuildInfo();
  console.log(`Build info: Yolo ${info.version}${info.commit ? ` (${info.commit})` : ""}, migrations through ${info.migrations.required}`);
}
